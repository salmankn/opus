// Builders for shippable digital products (P2):
// landing (self-contained static), webapp (full Next.js), expo (full Expo/RN).
// Every scaffold is a COMPLETE project: pinned deps, configs, routes/screens,
// README + vercel.json/EAS notes. `npm run build` (or static check) must pass.
// Artifacts live under <taskId>/product/<relative> so the sandbox builds
// exactly what we ship (single source of truth).
import { putArtifact } from "@platform/storage";
import type { ProductSpec } from "@platform/spec";

export const TEMPLATE_VERSIONS = { landing: "1.0.0", webapp: "1.0.0", expo: "1.0.0" } as const;

export interface Built { key: string; size: number; kind: string; }

function esc(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

function tsStr(s: string): string {
  return JSON.stringify(s);
}

function palette(style: ProductSpec["style"]): { bg: string; card: string; fg: string; accent: string } {
  if (style === "light") return { bg: "#f8fafc", card: "#ffffff", fg: "#0f172a", accent: "#2563eb" };
  if (style === "minimal") return { bg: "#ffffff", card: "#f1f5f9", fg: "#020617", accent: "#000000" };
  return { bg: "#0b0d12", card: "#141824", fg: "#e8eaf0", accent: "#7c9cff" };
}

// ---------- LANDING (self-contained, no CDN) ----------
function landingHtml(spec: ProductSpec, taskId: string): string {
  const p = palette(spec.style);
  const cards = spec.screens[0]?.bullets.length
    ? spec.screens[0].bullets.map(b => `<li class="card">${esc(b)}</li>`).join("")
    : spec.features.map(f => `<li class="card">${esc(f)}</li>`).join("");
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8"/>
<meta name="viewport" content="width=device-width,initial-scale=1"/>
<title>${esc(spec.name)}</title>
<meta name="description" content="${esc(spec.tagline || spec.name)}"/>
<style>
:root{color-scheme:${spec.style === "light" || spec.style === "minimal" ? "light" : "dark"}}
body{margin:0;font-family:system-ui,-apple-system,sans-serif;background:${p.bg};color:${p.fg}}
main{max-width:48rem;margin:0 auto;padding:2.5rem 1.25rem}
h1{font-size:2.5rem;line-height:1.1;margin:0}
.tag{opacity:.75;margin:.75rem 0 0}
ul{list-style:none;padding:0;margin:1.5rem 0 0;display:grid;gap:.75rem}
.card{background:${p.card};border-radius:.75rem;padding:1rem;border:1px solid rgba(127,127,127,.25)}
.cta{display:inline-block;margin-top:1.75rem;padding:.75rem 1.5rem;border-radius:.6rem;background:${p.accent};color:#fff;text-decoration:none;font-weight:600}
footer{margin-top:2.5rem;font-size:.8rem;opacity:.6}
</style>
</head>
<body>
<main>
<h1>${esc(spec.name)}</h1>
<p class="tag">${esc(spec.tagline || (spec.features[0] ?? ""))}</p>
<ul>${cards}</ul>
<a class="cta" href="#start">Get started</a>
<footer>Generated by Autonomous Work Platform (task ${esc(taskId)}, template landing@${TEMPLATE_VERSIONS.landing})</footer>
</main>
</body>
</html>`;
}

